#!/usr/bin/env python3
"""Icarus reference check of the array fault simulation (Phase 10).

  python3 sim/array_check.py R C --suite router [--n 20] [--centre 5] [--jobs N]

Same stimulus as sim/run_array.py (the fastsim.Stim rows, one hex word per
step: bit j = input port bit j, top bit = sample), testbench generated for
array_top, the flattened array netlist (synth/netlist_array_<R>x<C>.v) with
the X-pessimistic latch / flop models (sim/state.py). Checks:
  - the Icarus fault-free run equals the array model in every config,
  - for N random faults (plus some in the centre tile), every config: the
    Icarus status (D / P / U, +EARLY) equals the fast-kernel matrix
    (reports/array_<R>x<C>_<suite>_matrix.csv) wherever neither side timed out.
"""
from __future__ import annotations

import argparse
import csv
import random
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "configs"), str(ROOT / "sim"), str(ROOT / "sim" / "fastsim"), str(ROOT / "rtl")]
import fabric  # noqa: E402
import gen_array  # noqa: E402
import run_array  # noqa: E402
import simcore  # noqa: E402
import state  # noqa: E402

REPORTS = ROOT / "reports"
TIMEOUT_S = 600


def gen_tb(R: int, C: int, in_names: list[str], out_names: list[str], fabric: bool = False) -> str:
    _, ports, _ = (gen_array.generate_fabric if fabric else gen_array.generate)(R, C)
    width = {n: w for _, w, n in ports}

    def ref(bit: str) -> str:
        base = bit.split("[")[0]
        return base if width[base] == 1 else bit
    decl = [f"    {'reg' if d == 'input' else 'wire'} {'[%d:0] ' % (w - 1) if w > 1 else ''}{n};"
            for d, w, n in ports]
    conns = ",\n".join(f"        .{n}({n})" for _, _, n in ports)
    zero = "\n".join(f"        {n} = 0;" for d, _, n in ports if d == "input")
    SW = len(in_names) + 1
    assigns = "\n".join(f"            {ref(b)} = w[{j}];" for j, b in enumerate(in_names))
    n_out = len(out_names)
    sv = "{" + ", ".join(ref(b) for b in out_names) + "}"
    return f"""// Generated by sim/array_check.py: {R} x {C} array, stimulus rows of sim/run_array.py.
`timescale 1ns / 1ps
`default_nettype none
module tb;
{chr(10).join(decl)}
    array_top dut (
{conns}
    );
    reg [{SW - 1}:0] stim [0:4095];
    reg [{n_out - 1}:0] expv [0:1023];
    reg [{SW - 1}:0] w;
    reg [{n_out - 1}:0] sv;
    reg [8*512-1:0] stimfile, expfile;
    integer fault_id, nsteps, k, pu_v, ns, j, early;
`include "monitor.vh"
    initial begin
{zero}
        if (!$value$plusargs("STIM=%s", stimfile)) begin $display("ERROR missing +STIM"); $finish; end
        if (!$value$plusargs("NSTEPS=%d", nsteps)) begin $display("ERROR missing +NSTEPS"); $finish; end
        if (!$value$plusargs("FAULT=%d", fault_id)) fault_id = -1;
        early = $test$plusargs("EARLY");
        if (early) begin
            if (!$value$plusargs("EXP=%s", expfile)) begin $display("ERROR missing +EXP"); $finish; end
            $readmemb(expfile, expv);
        end
        $readmemh(stimfile, stim, 0, nsteps - 1);
        #1;
`include "faults.vh"
        #1;
`include "deposit.vh"
        ns = 0;
        for (k = 0; k < nsteps; k = k + 1) begin
            w = stim[k];
{assigns}
            #9;
            if (w[{SW - 1}]) begin
                sv = {sv};
                $display("S %b", sv);
                if (early) begin
                    for (j = 0; j < {n_out}; j = j + 1)
                        if ((expv[ns][j] === 1'b0 || expv[ns][j] === 1'b1) &&
                            (sv[j] === 1'b0 || sv[j] === 1'b1) && sv[j] !== expv[ns][j]) begin
                            $display("DET");
                            $finish;
                        end
                end
                ns = ns + 1;
            end
`include "segdump.vh"
            #1;
        end
`include "report.vh"
        $display("END");
        $finish;
    end
endmodule
"""


def write_stim(st, d: Path) -> tuple[Path, Path, int]:
    d.mkdir(parents=True, exist_ok=True)
    stim, expf = d / f"{st.name}.stim", d / f"{st.name}.expected"
    lines = []
    for r, s in zip(st.rows, st.sample):
        v = int(s) << len(st.in_names)
        for j, b in enumerate(r.tolist()):
            if b:
                v |= 1 << j
        lines.append(f"{v:x}")
    stim.write_text("\n".join(lines) + "\n")
    # $readmemb: MSB first = the last output; the testbench's sv puts out_names[0] at the MSB
    expf.write_text("\n".join(st.expected) + "\n")
    return stim, expf, len(lines)


_W: dict = {}


def _init(vvp, pa, golden):
    _W.update(vvp=vvp, pa=pa, golden=golden)


def _sim(fid: int):
    out = {}
    for c, pa in _W["pa"].items():
        r = simcore.run_vvp(Path(_W["vvp"]), pa, fid, timeout=TIMEOUT_S)
        out[c] = simcore.status(_W["golden"][c], r)
    return fid, out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("R", type=int)
    ap.add_argument("C", type=int)
    ap.add_argument("--suite", choices=["uniform", "router", "clocked", "lut", "merged"], default="router")
    ap.add_argument("--n", type=int, default=20)
    ap.add_argument("--centre", type=int, default=5, help="extra faults in the centre tile (R, C >= 3)")
    ap.add_argument("--jobs", type=int, default=3)
    ap.add_argument("--fabric", action="store_true")
    ap.add_argument("--max-configs", type=int, default=0, help="check only the first N configs")
    ap.add_argument("--tag", default="", help="router variant (sim/run_array.py --tag)")
    a = ap.parse_args()
    run_array.TAG = a.tag
    arr = fabric.Array(a.R, a.C, fabric=a.fabric)
    stims, _ = run_array.SUITES[a.suite](arr)
    if a.max_configs:
        stims = stims[:a.max_configs]
    faults = list(csv.DictReader((ROOT / "faults" / f"{arr.name}.csv").open()))
    matrix = {r["id"]: r for r in csv.DictReader((REPORTS / f"{arr.name}_{a.suite}{a.tag}_matrix.csv").open())}
    rnd = random.Random(11)
    sample = rnd.sample(faults, a.n)
    if a.R >= 3 and a.C >= 3 and not a.fabric:
        ctr = f"X{a.C // 2}Y{a.R // 2}."
        sample += rnd.sample([f for f in faults if f["path"].startswith(ctr)], a.centre)
    build = ROOT / "build" / "array" / f"{arr.name}_{a.suite}{a.tag}"
    elems = state.storage_elements(ROOT / "synth" / f"netlist_{arr.name}.json")
    t0 = time.time()
    vvp = simcore.compile_tb(build, gen_tb(a.R, a.C, stims[0].in_names, stims[0].out_names, a.fabric),
                             [ROOT / "synth" / f"netlist_{arr.name}.v", ROOT / "synth" / "simcells.v"],  # noqa: E501
                             sample, elems)
    print(f"{arr.name} {a.suite}: compiled {len(sample)} faults, {len(elems)} storage elements, "
          f"{time.time() - t0:.0f} s", flush=True)
    golden, pa = {}, {}
    for st in stims:
        stim, expf, n = write_stim(st, build / "stim")
        r = simcore.run_vvp(vvp, [f"+STIM={stim}", f"+NSTEPS={n}"])
        if r.samples != st.expected:
            bad = next(i for i, (x, y) in enumerate(zip(r.samples, st.expected)) if x != y) \
                if len(r.samples) == len(st.expected) else "count"
            raise SystemExit(f"{st.name}: Icarus fault-free run differs from the array model at sample {bad}")
        golden[st.name] = r.samples
        pa[st.name] = [f"+STIM={stim}", f"+NSTEPS={n}", f"+EXP={expf}", "+EARLY"]
    print(f"{arr.name} {a.suite}: Icarus fault-free = array model in all {len(stims)} configs "
          f"({time.time() - t0:.0f} s)", flush=True)
    with ProcessPoolExecutor(max_workers=a.jobs, initializer=_init, initargs=(str(vvp), pa, golden)) as ex:
        ref = dict(ex.map(_sim, [int(f["id"]) for f in sample]))
    bad, tdiff, cells = [], 0, 0
    for fid, st in ref.items():
        row = matrix[str(fid)]
        for c, s in st.items():
            cells += 1
            if s != row[c]:
                if "T" in (s, row[c]):
                    tdiff += 1
                else:
                    bad.append((fid, row["path"], row["polarity"], c, s, row[c]))
    print(f"{arr.name} {a.suite}: {len(sample)} faults x {len(stims)} configs = {cells} results, "
          f"{len(bad)} differ{f' ({tdiff} timeout-only)' if tdiff else ''}, {time.time() - t0:.0f} s")
    for b in bad[:10]:
        print("   ", b)
    if bad:
        sys.exit(1)


if __name__ == "__main__":
    main()
