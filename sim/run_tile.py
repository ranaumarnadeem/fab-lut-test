#!/usr/bin/env python3
"""LUT4AB tile: golden check, runtime estimate, fault simulation, exhaust.

  python3 sim/run_tile.py check
  python3 sim/run_tile.py estimate <netlist> [--n 40]
  python3 sim/run_tile.py faultsim <netlist> [--jobs N]
  python3 sim/run_tile.py exhaust <netlist> [--kmax 12]

netlist: tile_generic or tile_generic_br. Stimulus enters only through tile
ports: FrameData/FrameStrobe (configuration), UserCLK, Ci[0], and the tile
inputs of the test routing (configs/tile_routing.json); every other tile
input is held at 0. Observed: the 8 routed LUT outputs and Co[0].
Faulty runs use +EARLY (stop at the first definite mismatch) and a time
limit; a run that hits the limit is status T (counted as not detected).
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import random
import re
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "configs"))
sys.path.insert(0, str(ROOT / "sim"))
sys.path.insert(0, str(ROOT / "faults"))
import simcore  # noqa: E402
import state  # noqa: E402
import tile_configs as tc  # noqa: E402

BUILD = ROOT / "build"
REPORTS = ROOT / "reports"
NETLISTS = ["tile_generic", "tile_generic_br"]
SOURCES = {
    "tile_generic": ["synth/netlist_tile_generic.v", "synth/simcells.v"],
    "tile_generic_br": ["synth/netlist_tile_generic_br.v", "synth/simcells.v"],
}
CONFIGS = list(tc.TILE_CONFIGS)
# faultsim tries configs in this order and stops at the first D (status "-"
# for the configs not run); undetected faults always get all three.
RUN_ORDER = ["D1", "D0C", "BC1"]
TIMEOUT_S = 30.0
CHUNK = 1000  # faults per compiled testbench (the force case grows the run time)


def tile_ports() -> list[tuple[str, int, str]]:
    text = (ROOT / "rtl" / "tile_top.v").read_text()
    hdr = text.split(");", 1)[0]
    out = []
    for d, rng, n in re.findall(r"(input|output) wire (\[\d+:0\] )?(\w+)", hdr):
        out.append((d, int(rng.strip()[1:].split(":")[0]) + 1 if rng else 1, n))
    return out


def gen_tb() -> str:
    r = tc.ROUTING
    ports = tile_ports()
    decl, conns, assigns = [], [], []
    for d, w, n in ports:
        rng = f"[{w - 1}:0] " if w > 1 or n in ("Ci", "Co") else ""
        decl.append(f"    {'reg' if d == 'input' else 'wire'} {rng}{n};")
        conns.append(f"        .{n}({n})")
    zero = [f"        {n} = 0;" for d, w, n in ports if d == "input"]
    assigns.append("            FrameData = w[31:0];")
    assigns.append("            FrameStrobe = w[51:32];")
    for k, x in enumerate(tc.LUTS):
        for j in range(4):
            assigns.append(f"            {r['lut_inputs'][f'L{x}_I{j}']} = w[{52 + 4 * k + j}];")
    assigns.append("            Ci[0] = w[84];")
    assigns.append(f"            {r['lut_inputs']['J_SR_BEG[0]']} = w[85];")
    assigns.append(f"            {r['lut_inputs']['J_EN_BEG[0]']} = w[86];")
    assigns.append("            UserCLK = w[87];")
    obs = [r["lut_outputs"][f"L{x}_O"] for x in tc.LUTS] + ["Co[0]"]
    sv = "{" + ", ".join(obs) + "}"
    return f"""// Generated by sim/run_tile.py. Tile ports only; see run_tile.py docstring.
`timescale 1ns / 1ps
`default_nettype none
module tb;
{chr(10).join(decl)}
    tile_top dut (
{(','+chr(10)).join(conns)}
    );
    reg [127:0] stim [0:4095];
    reg [8:0] expv [0:1023];
    reg [127:0] w;
    reg [8:0] sv;
    reg [8*512-1:0] stimfile, expfile;
    integer fault_id, nsteps, k, pu_v, ns, j, early;
`include "monitor.vh"
    initial begin
{chr(10).join(zero)}
        if (!$value$plusargs("STIM=%s", stimfile)) begin $display("ERROR missing +STIM"); $finish; end
        if (!$value$plusargs("NSTEPS=%d", nsteps)) begin $display("ERROR missing +NSTEPS"); $finish; end
        if (!$value$plusargs("FAULT=%d", fault_id)) fault_id = -1;
        early = $test$plusargs("EARLY");
        if (early) begin
            if (!$value$plusargs("EXP=%s", expfile)) begin $display("ERROR missing +EXP"); $finish; end
            $readmemb(expfile, expv);
        end
        $readmemh(stimfile, stim, 0, nsteps - 1);
        #1;
`include "faults.vh"
        #1;
`include "deposit.vh"
        ns = 0;
        for (k = 0; k < nsteps; k = k + 1) begin
            w = stim[k];
{chr(10).join(assigns)}
            #9;
            if (w[88]) begin
                sv = {sv};
                $display("S %b", sv);
                if (early) begin
                    for (j = 0; j < 9; j = j + 1)
                        if ((expv[ns][j] === 1'b0 || expv[ns][j] === 1'b1) &&
                            (sv[j] === 1'b0 || sv[j] === 1'b1) && sv[j] !== expv[ns][j]) begin
                            $display("DET");
                            $finish;
                        end
                end
                ns = ns + 1;
            end
            #1;
        end
`include "report.vh"
        $display("END");
        $finish;
    end
endmodule
"""


def write_stimuli() -> dict[str, tuple[Path, int, list[str], Path]]:
    d = BUILD / "tile_stim"
    d.mkdir(parents=True, exist_ok=True)
    out = {}
    for name, f in tc.TILE_CONFIGS.items():
        seq = f()
        stim, expf = d / f"{name}.stim", d / f"{name}.expected"
        seq.write_stim(stim)
        exp = tc.tile_model(seq)
        expf.write_text("\n".join(exp) + "\n")
        out[name] = (stim, len(seq.steps), exp, expf)
    return out


def compile_netlist(netlist: str, faults: list[dict] | None,
                    tag: str = "") -> tuple[Path, list[state.Element]]:
    js = ROOT / "synth" / f"netlist_{netlist}.json"
    elems = state.storage_elements(js)
    vvp = simcore.compile_tb(BUILD / "sim" / f"{netlist}{tag}", gen_tb(),
                             [ROOT / s for s in SOURCES[netlist]], faults, elems)
    return vvp, elems


def compile_chunks(netlist: str, faults: list[dict]) -> dict[int, Path]:
    """fault id -> vvp of the chunk that holds it."""
    where = {}
    for c in range(0, len(faults), CHUNK):
        part = faults[c:c + CHUNK]
        vvp, _ = compile_netlist(netlist, part, tag=f"_c{c // CHUNK}")
        where.update({int(f["id"]): vvp for f in part})
    return where


def plusargs(stims, early: bool) -> dict[str, list[str]]:
    pa = {}
    for name, (stim, n, _exp, expf) in stims.items():
        pa[name] = [f"+STIM={stim}", f"+NSTEPS={n}"] + ([f"+EXP={expf}", "+EARLY"] if early else [])
    return pa


def golden_runs(vvp: Path, stims) -> dict[str, list[str]]:
    golden = {}
    for name, (stim, n, exp, _) in stims.items():
        r = simcore.run_vvp(vvp, [f"+STIM={stim}", f"+NSTEPS={n}"])
        if r.samples != exp:
            bad = [(i, g, e) for i, (g, e) in enumerate(zip(r.samples, exp)) if g != e][:5]
            raise SystemExit(f"{name}: golden differs from tile model: {bad}")
        if any(c not in "01" for s in r.samples for c in s):
            raise SystemExit(f"{name}: golden has X samples")
        if r.never_written:
            raise SystemExit(f"{name}: fault-free run leaves {len(r.never_written)} elements unwritten")
        golden[name] = r.samples
    return golden


def load_faults(netlist: str) -> list[dict]:
    return list(csv.DictReader((ROOT / "faults" / f"{netlist}.csv").open()))


def cmd_check(args) -> int:
    stims = write_stimuli()
    for netlist in NETLISTS:
        vvp, elems = compile_netlist(netlist, None)
        t0 = time.time()
        golden_runs(vvp, stims)
        print(f"{netlist}: golden = tile model on {CONFIGS}, {len(elems)} storage elements, "
              f"{time.time() - t0:.1f} s for 3 runs")
    return 0


_W: dict = {}


def _init(pa, golden):
    _W.update(pa=pa, golden=golden)


def _sim(job: tuple[str, int]) -> tuple[int, dict[str, str]]:
    vvp, fid = Path(job[0]), job[1]
    out = {c: "-" for c in CONFIGS}
    for c in RUN_ORDER:
        r = simcore.run_vvp(vvp, _W["pa"][c], fid, timeout=TIMEOUT_S)
        out[c] = simcore.status(_W["golden"][c], r)
        if out[c] == "D":
            break
    return fid, out


def cmd_estimate(args) -> int:
    stims = write_stimuli()
    faults = load_faults(args.netlist)
    vvp, _ = compile_netlist(args.netlist, faults)
    golden = golden_runs(vvp, stims)
    random.seed(1)
    sample = random.sample(faults, args.n)
    small, _ = compile_netlist(args.netlist, sample, tag="_est")
    _init(plusargs(stims, True), golden)
    t0 = time.time()
    res = [_sim((str(small), int(f["id"]))) for f in sample]
    dt = (time.time() - t0) / len(sample)
    workers = args.jobs
    total = dt * len(faults) / workers
    det = sum(1 for _, r in res if "D" in r.values())
    print(f"{args.netlist}: {len(faults)} faults, {dt:.2f} s per fault (stop at first D, serial), "
          f"estimate {total / 60:.1f} min on {workers} workers; sample detected {det}/{len(sample)}")
    return 0


def cmd_faultsim(args) -> int:
    netlist = args.netlist
    stims = write_stimuli()
    faults = load_faults(netlist)
    old_rows = None
    if args.only:
        # Rerun only the faults on matching nets and merge into the matrix.
        pat = re.compile(args.only)
        old_rows = {r["id"]: r for r in csv.DictReader((REPORTS / f"{netlist}_matrix.csv").open())}
        faults = [f for f in faults if pat.search(f["net"])]
    where = compile_chunks(netlist, faults)
    vvp0 = where[int(faults[0]["id"])]
    golden = golden_runs(vvp0, stims)
    for v in sorted(set(where.values())):
        if any(simcore.run_vvp(v, plusargs(stims, False)[c], -1).samples != golden[c] for c in CONFIGS):
            raise SystemExit(f"{v}: FAULT=-1 run differs from golden")
    print(f"{netlist}: golden OK; {len(faults)} faults, {len(set(where.values()))} chunks", flush=True)
    results: dict[int, dict[str, str]] = {}
    t0 = time.time()
    jobs = [(str(where[int(f["id"])]), int(f["id"])) for f in faults]
    with ProcessPoolExecutor(max_workers=args.jobs, initializer=_init,
                             initargs=(plusargs(stims, True), golden)) as ex:
        for k, (fid, res) in enumerate(ex.map(_sim, jobs, chunksize=16)):
            results[fid] = res
            if (k + 1) % 1000 == 0:
                el = time.time() - t0
                print(f"  {k + 1}/{len(faults)}  {el / 60:.1f} min, eta {el / (k + 1) * (len(faults) - k - 1) / 60:.1f} min",
                      flush=True)
    REPORTS.mkdir(exist_ok=True)
    rows = {}
    for flt in faults:
        r = results[int(flt["id"])]
        v = set(r.values())
        anyd = "D" if "D" in v else "P" if "P" in v else "T" if "T" in v else "U"
        rows[flt["id"]] = {"id": flt["id"], "path": flt["path"], "polarity": flt["polarity"],
                           "type": flt["type"], **r, "any": anyd}
    if old_rows is not None:
        changes = [(old_rows[i], rows[i]) for i in rows
                   if any(old_rows[i][c] != rows[i][c] for c in CONFIGS + ["any"])]
        with (REPORTS / f"{netlist}_rerun_changes.csv").open("w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["id", "path", "polarity", "type",
                        *[f"old_{c}" for c in CONFIGS + ["any"]], *[f"new_{c}" for c in CONFIGS + ["any"]]])
            for o, n in changes:
                w.writerow([n["id"], n["path"], n["polarity"], n["type"],
                            *[o[c] for c in CONFIGS + ["any"]], *[n[c] for c in CONFIGS + ["any"]]])
        print(f"{netlist}: reran {len(rows)} faults, {len(changes)} changed "
              f"(reports/{netlist}_rerun_changes.csv)")
        old_rows.update(rows)
        rows = old_rows
    with (REPORTS / f"{netlist}_matrix.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "path", "polarity", "type", *CONFIGS, "any"])
        for i in sorted(rows, key=int):
            r = rows[i]
            w.writerow([r["id"], r["path"], r["polarity"], r["type"], *[r[c] for c in CONFIGS], r["any"]])
    print(f"{netlist}: done in {(time.time() - t0) / 60:.1f} min")
    return 0


def cmd_exhaust(args) -> int:
    netlist = args.netlist
    matrix = list(csv.DictReader((REPORTS / f"{netlist}_matrix.csv").open()))
    stims = write_stimuli()
    jobs = []
    for row in matrix:
        p = [c for c in CONFIGS if row[c] == "P"]
        if p:
            jobs.append((int(row["id"]), p, [c for c in CONFIGS if row[c] == "D"]))
    todo = {j[0] for j in jobs}
    faults = [f for f in load_faults(netlist) if int(f["id"]) in todo]
    vvp, elems = compile_netlist(netlist, faults, tag="_exhaust")
    golden = golden_runs(vvp, stims)
    print(f"{netlist}: {len(jobs)} faults with P status")
    t0 = time.time()
    recs = simcore.exhaust(vvp, plusargs(stims, True), golden, jobs, args.kmax, args.jobs,
                           timeout=TIMEOUT_S)
    by_id = {r["id"]: r for r in matrix}
    for rec in recs:
        row = by_id[str(rec["id"])]
        rec.update(path=row["path"], polarity=row["polarity"], type=row["type"],
                   element_labels=[elems[i].label for i in rec["elements"]])
    (REPORTS / f"{netlist}_exhaust.json").write_text(json.dumps(
        {"configs": CONFIGS, "kmax": args.kmax, "faults": recs}, indent=1))
    n_big = sum(1 for r in recs if r["assignments"] is None and not r.get("timeout"))
    print(f"{netlist}: exhaust done in {(time.time() - t0) / 60:.1f} min; "
          f"{n_big} faults not enumerated (k > {args.kmax})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check")
    for cmd in ("estimate", "faultsim", "exhaust"):
        p = sub.add_parser(cmd)
        p.add_argument("netlist", choices=NETLISTS)
        p.add_argument("--jobs", type=int, default=os.cpu_count())
        if cmd == "faultsim":
            p.add_argument("--only", help="regex on the fault net: rerun those, merge into the matrix")
        if cmd == "estimate":
            p.add_argument("--n", type=int, default=40)
        if cmd == "exhaust":
            p.add_argument("--kmax", type=int, default=12)
    args = ap.parse_args()
    return {"check": cmd_check, "estimate": cmd_estimate, "faultsim": cmd_faultsim,
            "exhaust": cmd_exhaust}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
