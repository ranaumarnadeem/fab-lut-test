#!/usr/bin/env python3
"""LUT4AB tile, switch-matrix baseline configs (Phase 8 steps 2, 3).

  python3 sim/run_sm.py check
  python3 sim/run_sm.py estimate <netlist> [--n 40]
  python3 sim/run_sm.py faultsim <netlist> [--jobs N] [--sequence SM00 ...]
  python3 sim/run_sm.py exhaust <netlist>
  --suite router (any command): the routed configs of configs/sm_router.py
  (reports/<netlist>_rt_matrix.csv, _rt_seq_)
  --suite clocked: registered-LUT SR / EN configs of configs/sm_clocked.py
  (reports/<netlist>_ck_matrix.csv; no sequence mode)

Same machinery as sim/run_tile.py (chunked fault simulation, strict
3-valued D / P / U / T, +EARLY, time limit, monitors, deposits), with the
configs of configs/sm_configs.py: every tile input port is driven (unique
codes and complements), every tile output port is observed at every sample.
This is tile-level observability, an upper bound on what a fabric test sees
(in a fabric the outputs reach the tester only through neighbouring tiles).
Reports: reports/<netlist>_sm_matrix.csv (sequence mode: _sm_seq_).
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

if "--suite" in sys.argv:   # before sm_configs is imported: it reads SM_SUITE
    _k = sys.argv.index("--suite")
    os.environ["SM_SUITE"] = sys.argv[_k + 1]
    del sys.argv[_k:_k + 2]

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "sim"), str(ROOT / "configs")]
import run_tile as rt  # noqa: E402
import simcore  # noqa: E402
import sm_configs as sc  # noqa: E402

STIM_DIR = ROOT / "build" / "sm_stim"
N_OUT = len(sc.OUTPUTS)


def gen_tb() -> str:
    ports = rt.tile_ports()
    decl, conns = [], []
    for d, w, n in ports:
        rng = f"[{w - 1}:0] " if w > 1 or n in ("Ci", "Co") else ""
        decl.append(f"    {'reg' if d == 'input' else 'wire'} {rng}{n};")
        conns.append(f"        .{n}({n})")
    zero = [f"        {n} = 0;" for d, w, n in ports if d == "input"]
    assigns = ["            FrameData = w[31:0];", "            FrameStrobe = w[51:32];"]
    assigns += [f"            {p} = w[{52 + j}];" for j, p in enumerate(sc.INPUTS)]
    assigns.append("            UserCLK = w[253];")
    sv = "{" + ", ".join(sc.OUTPUTS) + "}"
    return f"""// Generated by sim/run_sm.py. All tile inputs driven, all tile outputs observed.
`timescale 1ns / 1ps
`default_nettype none
module tb;
{chr(10).join(decl)}
    tile_top dut (
{(','+chr(10)).join(conns)}
    );
    reg [255:0] stim [0:8191];
    reg [{N_OUT - 1}:0] expv [0:4095];
    reg [255:0] w;
    reg [{N_OUT - 1}:0] sv;
    reg [8*512-1:0] stimfile, expfile;
    integer fault_id, nsteps, k, pu_v, ns, j, early;
`include "monitor.vh"
    initial begin
{chr(10).join(zero)}
        if (!$value$plusargs("STIM=%s", stimfile)) begin $display("ERROR missing +STIM"); $finish; end
        if (!$value$plusargs("NSTEPS=%d", nsteps)) begin $display("ERROR missing +NSTEPS"); $finish; end
        if (!$value$plusargs("FAULT=%d", fault_id)) fault_id = -1;
        early = $test$plusargs("EARLY");
        if (early) begin
            if (!$value$plusargs("EXP=%s", expfile)) begin $display("ERROR missing +EXP"); $finish; end
            $readmemb(expfile, expv);
        end
        $readmemh(stimfile, stim, 0, nsteps - 1);
        #1;
`include "faults.vh"
        #1;
`include "deposit.vh"
        ns = 0;
        for (k = 0; k < nsteps; k = k + 1) begin
            w = stim[k];
{chr(10).join(assigns)}
            #9;
            if (w[254]) begin
                sv = {sv};
                $display("S %b", sv);
                if (early) begin
                    for (j = 0; j < {N_OUT}; j = j + 1)
                        if ((expv[ns][j] === 1'b0 || expv[ns][j] === 1'b1) &&
                            (sv[j] === 1'b0 || sv[j] === 1'b1) && sv[j] !== expv[ns][j]) begin
                            $display("DET");
                            $finish;
                        end
                end
                ns = ns + 1;
            end
`include "segdump.vh"
            #1;
        end
`include "report.vh"
        $display("END");
        $finish;
    end
endmodule
"""


CONFIG_FUNCS = dict(sc.SM_CONFIGS if sc.SUITE == "clocked" else sc.BASE_SM_CONFIGS)
TAG = {"router": "_rt", "clocked": "_ck"}.get(sc.SUITE, "_sm")
SEQ = "SEQ_RT" if sc.SUITE == "router" else "SEQ_SM"   # name -> SMSeq factory (one sequence in sequence mode)


def write_stimuli() -> dict[str, tuple[Path, int, list[str], Path]]:
    STIM_DIR.mkdir(parents=True, exist_ok=True)
    out = {}
    for name, f in CONFIG_FUNCS.items():
        seq = f()
        rt.assert_loop_free(name, seq)
        if any(getattr(seq, "transition_bad", ())):
            raise SystemExit(f"{name}: a reconfiguration passes through a loop "
                             f"({seq.transition_bad}); not simulating")
        stim, expf = STIM_DIR / f"{name}.stim", STIM_DIR / f"{name}.expected"
        seq.write_stim(stim)
        exp = sc.expected(seq)
        expf.write_text("\n".join(exp) + "\n")
        out[name] = (stim, len(seq.steps), exp, expf)
    return out


def golden_runs(vvp: Path, stims) -> dict[str, list[str]]:
    """Fault-free run of every config must equal the model, with no X sample
    and every config latch written (the flops are not clocked: UserCLK = 0)."""
    golden = {}
    for name, (stim, n, exp, _) in stims.items():
        r = simcore.run_vvp(vvp, [f"+STIM={stim}", f"+NSTEPS={n}"])
        if r.samples != exp:
            bad = [(i, [sc.OUTPUTS[j] for j, (g, e) in enumerate(zip(gs, es)) if g != e][:6])
                   for i, (gs, es) in enumerate(zip(r.samples, exp)) if gs != es][:4]
            raise SystemExit(f"{name}: golden differs from the model: {bad}")
        if any(c not in "01" for s in r.samples for c in s):
            raise SystemExit(f"{name}: golden has X samples")
        if not r.never_def_written <= FLOPS:
            raise SystemExit(f"{name}: latches never written: {sorted(r.never_def_written - FLOPS)[:8]}")
        golden[name] = r.samples
    return golden


def _setup() -> None:
    """Point run_tile at the switch-matrix configs (own build dir, file tag)."""
    rt.gen_tb = gen_tb
    rt.write_stimuli = write_stimuli
    rt.golden_runs = golden_runs
    rt.BUILD = ROOT / "build" / {"router": "rt", "clocked": "ck"}.get(sc.SUITE, "sm")
    rt.CONFIGS = list(sc.SM_CONFIGS)
    rt.RUN_ORDER = list(sc.SM_CONFIGS)
    rt.TAG = TAG
    rt.tc.TILE_CONFIGS = dict(sc.SM_CONFIGS)
    import loop_check
    ch = loop_check.Checker("tile_generic")
    ch.held0 = []                                  # every tile input is driven
    ch.obs = list(sc.OUTPUTS)
    ch.obs_bits = {ch.g.port_bits[o] for o in ch.obs}
    rt._LOOP_CHECKER = ch


def _flops() -> frozenset[int]:
    import state
    js = ROOT / "synth" / "netlist_tile_generic.json"
    return frozenset(e.index for e in state.storage_elements(js) if e.kind == "flop")


FLOPS = _flops()


def main() -> int:
    global CONFIG_FUNCS
    _setup()
    argv = sys.argv[1:]
    if "--sequence" in argv:
        # sequence mode: SM configs as one run from one power-up (default: all, in order)
        k = argv.index("--sequence")
        rest = argv[k + 1:]
        names = []
        for a in rest:
            if a not in sc.BASE_SM_CONFIGS:
                break
            names.append(a)
        argv = argv[:k] + rest[len(names):]
        names = names or list(sc.BASE_SM_CONFIGS)
        CONFIG_FUNCS = {SEQ: (lambda: sc.sequence(names))}
        rt.tc.TILE_CONFIGS = dict(CONFIG_FUNCS)
        rt.CONFIGS, rt.RUN_ORDER, rt.TAG = [SEQ], [SEQ], TAG + "_seq"
    sys.argv = [sys.argv[0]] + argv
    return rt.main()


if __name__ == "__main__":
    sys.exit(main())
