#!/usr/bin/env python3
"""Bundle the sky130_fd_sc_hd functional Verilog models a netlist needs.

For every sized cell type in the yosys JSON (e.g. sky130_fd_sc_hd__nand2_1)
this emits, once each and with `include lines removed:
  the UDPs the functional model includes, the functional model of the base
  cell, and the sized wrapper (non USE_POWER_PINS branch).
The result is a single file that iverilog can read without include paths.
"""
import argparse
import json
import re
from pathlib import Path

PREFIX = "sky130_fd_sc_hd__"
INCLUDE_RE = re.compile(r'^\s*`include\s+"([^"]+)"\s*$', re.M)
SIZED_RE = re.compile(rf"^{PREFIX}(\w+?)_(\d+)$")


def strip_includes(text: str) -> tuple[str, list[str]]:
    incs = INCLUDE_RE.findall(text)
    return INCLUDE_RE.sub("", text), incs


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("netlist_json", type=Path)
    ap.add_argument("--sc-hd", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    design = json.loads(args.netlist_json.read_text())
    types = set()
    for mod in design["modules"].values():
        for cell in mod.get("cells", {}).values():
            if cell["type"].startswith(PREFIX):
                types.add(cell["type"])

    emitted: set[Path] = set()
    chunks: list[str] = []

    def emit(path: Path) -> None:
        path = path.resolve()
        if path in emitted:
            return
        if not path.is_file():
            raise SystemExit(f"missing model file {path}")
        body, incs = strip_includes(path.read_text())
        for inc in incs:
            # UDP includes are relative to the including file
            if "/models/" in inc or inc.startswith("../"):
                emit(path.parent / inc)
        emitted.add(path)
        chunks.append(f"// ---- {path.relative_to(args.sc_hd.resolve())}\n{body}\n")

    for t in sorted(types):
        m = SIZED_RE.match(t)
        if not m:
            raise SystemExit(f"cannot parse cell type {t}")
        base = m.group(1)
        cell_dir = args.sc_hd / "cells" / base
        emit(cell_dir / f"{PREFIX}{base}.functional.v")
        emit(cell_dir / f"{t}.v")

    header = (
        "// Generated by synth/bundle_sky130_models.py\n"
        f"// Cells: {', '.join(sorted(types))}\n"
    )
    args.out.write_text(header + "".join(chunks))


if __name__ == "__main__":
    main()
