#!/usr/bin/env python3
"""Generate lut_cell_top.v and configs/la_bitmap.csv from a FABulous ConfigMem.

Reads the latch instances in the generated <Tile>_ConfigMem.v (non-EMULATION
branch) and keeps those that drive ConfigBits[base .. base+width-1], i.e. the
slice wired to one LUT4c_frame_config_dffesr BEL in the tile.
"""
import argparse
import csv
import re
from pathlib import Path

LATCH_RE = re.compile(
    r"config_latch\s+(\w+)\s*\(\s*"
    r"\.D\(FrameData\[(\d+)\]\),\s*"
    r"\.E\(FrameStrobe\[(\d+)\]\),\s*"
    r"\.Q\(ConfigBits\[(\d+)\]\),\s*"
    r"\.QN\(ConfigBits_N\[(\d+)\]\)\s*\);"
)


def parse_configmem(path: Path) -> dict[int, tuple[str, int, int]]:
    text = path.read_text()
    if "`else" not in text:
        raise SystemExit(f"{path}: no non-EMULATION branch found")
    body = text.split("`else", 1)[1]
    mapping = {}
    for inst, d, s, q, qn in LATCH_RE.findall(body):
        if q != qn:
            raise SystemExit(f"{inst}: Q index {q} != QN index {qn}")
        mapping[int(q)] = (inst, int(d), int(s))
    return mapping


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("configmem", type=Path)
    ap.add_argument("--base", type=int, default=0)
    ap.add_argument("--width", type=int, default=19)
    ap.add_argument("--out-v", type=Path, required=True)
    ap.add_argument("--out-csv", type=Path, required=True)
    args = ap.parse_args()

    mapping = parse_configmem(args.configmem)
    bits = []
    for local in range(args.width):
        g = args.base + local
        if g not in mapping:
            raise SystemExit(f"ConfigBits[{g}] has no latch in {args.configmem}")
        inst, d, s = mapping[g]
        bits.append((local, g, inst, d, s))

    fd = [b[3] for b in bits]
    fs = [b[4] for b in bits]
    fd_hi, fd_lo = max(fd), min(fd)
    fs_hi, fs_lo = max(fs), min(fs)

    with args.out_csv.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["config_bit", "tile_config_bit", "latch_inst", "frame_data_bit", "frame_strobe"])
        for local, g, inst, d, s in bits:
            w.writerow([local, g, inst, d, s])

    lines = [
        "// Generated by rtl/gen_wrapper.py from",
        f"//   {args.configmem.name} (ConfigBits[{args.base + args.width - 1}:{args.base}])",
        "// Single LUT4c_frame_config_dffesr BEL with its own config latches.",
        "// FrameData/FrameStrobe keep tile bit indices; unused bits in the ranges are",
        "// left unconnected.",
        "`default_nettype none",
        "",
        "module lut_cell_top (",
        f"    input  wire [{fd_hi}:{fd_lo}] FrameData,",
        f"    input  wire [{fs_hi}:{fs_lo}] FrameStrobe,",
        "    input  wire [3:0] I,",
        "    input  wire Ci,",
        "    input  wire SR,",
        "    input  wire EN,",
        "    input  wire UserCLK,",
        "    output wire O,",
        "    output wire Co",
        ");",
        f"    wire [{args.width - 1}:0] ConfigBits;",
        f"    wire [{args.width - 1}:0] ConfigBits_N;",
        "",
    ]
    for local, g, inst, d, s in bits:
        lines += [
            f"    // ConfigBits[{local}] = tile ConfigBits[{g}]",
            f"    config_latch {inst} (",
            f"        .D(FrameData[{d}]),",
            f"        .E(FrameStrobe[{s}]),",
            f"        .Q(ConfigBits[{local}]),",
            f"        .QN(ConfigBits_N[{local}])",
            "    );",
            "",
        ]
    lines += [
        "    LUT4c_frame_config_dffesr Inst_LA_LUT4c_frame_config_dffesr (",
        "        .I(I),",
        "        .O(O),",
        "        .Ci(Ci),",
        "        .Co(Co),",
        "        .SR(SR),",
        "        .EN(EN),",
        "        .UserCLK(UserCLK),",
        "        .ConfigBits(ConfigBits)",
        "    );",
        "endmodule",
        "`resetall",
        "",
    ]
    args.out_v.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
