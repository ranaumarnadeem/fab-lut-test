#!/usr/bin/env python3
"""Generate rtl/tile_top.v: the generated tile with every port passed out.

The wrapper adds nothing: all tile ports (routing wires, Ci/Co, FrameData,
FrameStrobe, UserCLK and the pass-through outputs) become wrapper ports, so
synthesis cannot constant-fold unused routing. The testbench decides which
ports it drives (unused inputs held at 0) and observes (test-routing
outputs and Co only).
"""
import argparse
import re
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("tile_v", type=Path)
ap.add_argument("--tile", default="LUT4AB")
ap.add_argument("--out", type=Path, required=True)
args = ap.parse_args()

text = args.tile_v.read_text()
m = re.search(rf"module {args.tile}\s*#\((.*?)\)\s*\((.*?)\);", text, re.S)
params = dict(re.findall(r"parameter\s+(?:\[[^\]]+\]\s*)?(\w+)\s*=\s*(\d+)", m.group(1)))
ports = re.findall(r"(input|output)\s*(\[[^\]]+\])?\s*(\w+)", m.group(2))


def width(rng: str) -> str:
    if not rng:
        return ""
    for k, v in params.items():
        rng = rng.replace(k, v)
    hi, lo = rng.strip("[]").split(":")
    return f"[{eval(hi, {}, {})}:{eval(lo, {}, {})}] "  # only integer arithmetic from the header


lines = [f"// Generated by rtl/gen_tile_top.py from {args.tile_v.name}. Pass-through wrapper.",
         "`default_nettype none", "", "module tile_top ("]
decl = [f"    {d} wire {width(r)}{n}" for d, r, n in ports]
lines.append(",\n".join(decl))
lines += [");", f"    {args.tile} Inst_{args.tile} ("]
lines.append(",\n".join(f"        .{n}({n})" for _, _, n in ports))
lines += ["    );", "endmodule", "`resetall", ""]
args.out.write_text("\n".join(lines))
print(f"{args.out}: {len(ports)} ports")
