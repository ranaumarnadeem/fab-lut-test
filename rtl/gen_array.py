#!/usr/bin/env python3
"""Generate rtl/array_<R>x<C>.v: an R x C array of LUT4AB tiles (Phase 10).

Each tile is the synthesized tile netlist (module tile_top of
synth/netlist_tile_generic.v), instance X<x>Y<y> (x = column from the west,
y = row from the north, as in FABulous). Wiring as FABulous generates it
(ext/demo/Fabric/eFPGA.v, e.g. Tile_X1Y2_LUT4AB): every <D>END / <D>MID input
bus takes the neighbour's <D>BEG / <D>BEGb output bus whole:
  from the south tile (x, y+1): N1END, N2MID, N2END, N4END, NN4END, Ci <- Co,
      UserCLK <- UserCLKo, FrameStrobe <- FrameStrobe_O
  from the west tile (x-1, y):  E1END, E2MID, E2END, EE4END, E6END,
      FrameData <- FrameData_O
  from the north tile (x, y-1): S1END, S2MID, S2END, S4END, SS4END
  from the east tile (x+1, y):  W1END, W2MID, W2END, WW4END, W6END
Border: an input with no neighbour inside the array is an array input port
X<x>Y<y>_<port>; a routing output with no reader inside is an array output
port X<x>Y<y>_<port> (the tester reaches the array border). Config: one
FrameData_R<y> bus per row (into the west tile), one FrameStrobe_C<x> bus per
column (into the south tile), one UserCLK into every south tile. FrameData_O
(east), FrameStrobe_O and UserCLKo (north) of the border tiles are left
unconnected.

Run: python3 rtl/gen_array.py R C   (writes rtl/array_<R>x<C>.v)
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# input port -> (dx, dy, neighbour output port)
FROM = {
    "N1END": (0, 1, "N1BEG"), "N2MID": (0, 1, "N2BEG"), "N2END": (0, 1, "N2BEGb"),
    "N4END": (0, 1, "N4BEG"), "NN4END": (0, 1, "NN4BEG"), "Ci": (0, 1, "Co"),
    "UserCLK": (0, 1, "UserCLKo"), "FrameStrobe": (0, 1, "FrameStrobe_O"),
    "E1END": (-1, 0, "E1BEG"), "E2MID": (-1, 0, "E2BEG"), "E2END": (-1, 0, "E2BEGb"),
    "EE4END": (-1, 0, "EE4BEG"), "E6END": (-1, 0, "E6BEG"), "FrameData": (-1, 0, "FrameData_O"),
    "S1END": (0, -1, "S1BEG"), "S2MID": (0, -1, "S2BEG"), "S2END": (0, -1, "S2BEGb"),
    "S4END": (0, -1, "S4BEG"), "SS4END": (0, -1, "SS4BEG"),
    "W1END": (1, 0, "W1BEG"), "W2MID": (1, 0, "W2BEG"), "W2END": (1, 0, "W2BEGb"),
    "WW4END": (1, 0, "WW4BEG"), "W6END": (1, 0, "W6BEG"),
}
CONFIG_OUT = {"FrameData_O", "FrameStrobe_O", "UserCLKo"}


def tile_ports() -> list[tuple[str, int, str]]:
    """(direction, width, name) of tile_top, from the synthesized netlist."""
    v = (ROOT / "synth" / "netlist_tile_generic.v").read_text()
    body = v[v.index("module tile_top"):v.index("endmodule")]
    out = []
    for d, hi, lo, n in re.findall(r"^\s*(input|output)\s*(?:\[(\d+):(\d+)\])?\s*(\w+);", body, re.M):
        out.append((d, int(hi) - int(lo) + 1 if hi else 1, n))
    return out


def generate(R: int, C: int) -> tuple[str, list, list]:
    ports = tile_ports()
    width = {n: w for _, w, n in ports}
    outs = {n for d, _, n in ports if d == "output"}
    readers = {src: (dx, dy, dst) for dst, (dx, dy, src) in FROM.items()}
    top_ports, wires, inst = [], [], []
    for y in range(R):
        for x in range(C):
            t = f"X{x}Y{y}"
            conns = []
            for d, w, n in ports:
                rng = f"[{w - 1}:0] " if w > 1 else ""
                if d == "input":
                    dx, dy, src = FROM[n]
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < C and 0 <= ny < R:
                        conns.append((n, f"X{nx}Y{ny}_{src}"))
                    elif n == "FrameData":
                        conns.append((n, f"FrameData_R{y}"))
                    elif n == "FrameStrobe":
                        conns.append((n, f"FrameStrobe_C{x}"))
                    elif n == "UserCLK":
                        conns.append((n, "UserCLK"))
                    else:
                        top_ports.append(("input", w, f"{t}_{n}"))
                        conns.append((n, f"{t}_{n}"))
                else:
                    sig = f"{t}_{n}"
                    dx, dy, _dst = readers[n]
                    # reader of this output sits at (x - dx, y - dy)
                    rx, ry = x - dx, y - dy
                    inside = 0 <= rx < C and 0 <= ry < R
                    if inside or n in CONFIG_OUT:
                        wires.append((w, sig))
                    else:
                        top_ports.append(("output", w, sig))
                    conns.append((n, sig))
            inst.append((t, conns))
    cfg = [("input", 32, f"FrameData_R{y}") for y in range(R)] + \
          [("input", 20, f"FrameStrobe_C{x}") for x in range(C)] + [("input", 1, "UserCLK")]
    top_ports = cfg + top_ports
    lines = [f"// Generated by rtl/gen_array.py: {R} x {C} LUT4AB array, FABulous wiring.",
             "`default_nettype none", "", "module array_top ("]
    lines.append(",\n".join(f"    {d} wire {'[%d:0] ' % (w - 1) if w > 1 else ''}{n}" for d, w, n in top_ports))
    lines.append(");")
    for w, n in wires:
        lines.append(f"    wire {'[%d:0] ' % (w - 1) if w > 1 else ''}{n};")
    for t, conns in inst:
        lines.append(f"    tile_top {t} (")
        lines.append(",\n".join(f"        .{p}({s})" for p, s in conns))
        lines.append("    );")
    lines.append("endmodule")
    del width, outs
    return "\n".join(lines) + "\n", top_ports, inst


# Termination tiles (rtl/term/*_switch_matrix.list): pure wires, bit order reversed.
# N_term above the north row: <S>END of the tile <- its own <N>BEG, reversed.
N_TERM = {"S1END": "N1BEG", "S2MID": "N2BEG", "S2END": "N2BEGb", "S4END": "N4BEG", "SS4END": "NN4BEG"}
# S_term below the south row: <N>END of the tile <- its own <S>BEG, reversed; Ci <- GND (Co0, GND0).
S_TERM = {"N1END": "S1BEG", "N2MID": "S2BEG", "N2END": "S2BEGb", "N4END": "S4BEG", "NN4END": "SS4BEG"}
# W_IO west of column 0: tile <E>END <- W_IO <E>BEG, W_IO <W>END <- tile <W>BEG (same names).
WIO_E = {"E1END": "E1BEG", "E2MID": "E2BEG", "E2END": "E2BEGb", "EE4END": "EE4BEG", "E6END": "E6BEG"}
WIO_W = {"W1END": "W1BEG", "W2MID": "W2BEG", "W2END": "W2BEGb", "WW4END": "WW4BEG", "W6END": "W6BEG"}


def wio_ports() -> list[tuple[str, int, str]]:
    v = (ROOT / "rtl" / "W_IO" / "wio_top.v").read_text()
    return [(d, int(hi) - int(lo) + 1 if hi else 1, n) for d, hi, lo, n in
            re.findall(r"^\s*(input|output) wire (?:\[(\d+):(\d+)\] )?(\w+)", v, re.M)]


def generate_fabric(R: int, C: int) -> tuple[str, list, list]:
    """R x C LUT4AB tiles as in a FABulous fabric: W_IO column on the west
    (instances IOY<y>), N_term / S_term rows as wires, east edge open (W*END
    inputs 0, E*BEG outputs unobserved). Array ports: the W_IO pads and
    config-access bits, FrameData_R<y>, FrameStrobe_C<x> and FrameStrobe_CW
    (W_IO column), UserCLK."""
    ports = tile_ports()
    width = {n: w for _, w, n in ports}
    wports = wio_ports()
    top_ports, wires, inst, assigns = [], [], [], []
    for y in range(R):
        for x in range(C):
            t = f"X{x}Y{y}"
            conns = []
            for d, w, n in ports:
                if d == "output":
                    sig = f"{t}_{n}"
                    wires.append((w, sig))
                    conns.append((n, sig))
                    continue
                dx, dy, src = FROM[n]
                nx, ny = x + dx, y + dy
                if 0 <= nx < C and 0 <= ny < R:
                    conns.append((n, f"X{nx}Y{ny}_{src}"))
                elif n == "FrameData":
                    conns.append((n, f"IOY{y}_FrameData_O" if x == 0 else f"FrameData_R{y}"))
                elif n == "FrameStrobe":
                    conns.append((n, f"FrameStrobe_C{x}"))
                elif n == "UserCLK":
                    conns.append((n, "UserCLK"))
                elif n in N_TERM and y == 0:
                    src = f"{t}_{N_TERM[n]}"
                    conns.append((n, "{" + ", ".join(f"{src}[{w - 1 - k}]" for k in reversed(range(w))) + "}"))
                elif n in S_TERM and y == R - 1:
                    src = f"{t}_{S_TERM[n]}"
                    conns.append((n, "{" + ", ".join(f"{src}[{w - 1 - k}]" for k in reversed(range(w))) + "}"))
                elif n == "Ci" and y == R - 1:
                    conns.append((n, "1'b0"))
                elif n in WIO_E and x == 0:
                    conns.append((n, f"IOY{y}_{WIO_E[n]}"))
                else:   # east edge: no neighbour
                    conns.append((n, f"{w}'b0"))
            inst.append(("tile_top", t, conns))
        t = f"IOY{y}"
        conns = []
        for d, w, n in wports:
            if d == "input":
                if n in WIO_W:
                    conns.append((n, f"X0Y{y}_{WIO_W[n]}"))
                elif n == "FrameData":
                    conns.append((n, f"FrameData_R{y}"))
                elif n == "FrameStrobe":
                    conns.append((n, f"IOY{y + 1}_FrameStrobe_O" if y < R - 1 else "FrameStrobe_CW"))
                elif n == "UserCLK":
                    conns.append((n, f"IOY{y + 1}_UserCLKo" if y < R - 1 else "UserCLK"))
                else:   # pads in
                    top_ports.append(("input", w, f"{t}_{n}"))
                    conns.append((n, f"{t}_{n}"))
            else:
                sig = f"{t}_{n}"
                if n.endswith("_top") or "C_bit" in n:
                    top_ports.append(("output", w, sig))
                else:
                    wires.append((w, sig))
                conns.append((n, sig))
        inst.append(("wio_top", t, conns))
    cfg = [("input", 32, f"FrameData_R{y}") for y in range(R)] + \
          [("input", 20, f"FrameStrobe_C{x}") for x in range(C)] + [("input", 20, "FrameStrobe_CW"),
                                                                     ("input", 1, "UserCLK")]
    top_ports = cfg + top_ports
    lines = [f"// Generated by rtl/gen_array.py --fabric: {R} x {C} LUT4AB, W_IO west, N / S term, east open.",
             "`default_nettype none", "", "module array_top ("]
    lines.append(",\n".join(f"    {d} wire {'[%d:0] ' % (w - 1) if w > 1 else ''}{n}" for d, w, n in top_ports))
    lines.append(");")
    for w, n in wires:
        lines.append(f"    wire {'[%d:0] ' % (w - 1) if w > 1 else ''}{n};")
    for mod, t, conns in inst:
        lines.append(f"    {mod} {t} (")
        lines.append(",\n".join(f"        .{p}({s})" for p, s in conns))
        lines.append("    );")
    lines += assigns + ["endmodule"]
    del width
    return "\n".join(lines) + "\n", top_ports, inst


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("R", type=int)
    ap.add_argument("C", type=int)
    ap.add_argument("--fabric", action="store_true", help="W_IO west, N / S term, east open")
    a = ap.parse_args()
    text, ports, _ = (generate_fabric if a.fabric else generate)(a.R, a.C)
    out = ROOT / "rtl" / f"{'fabric' if a.fabric else 'array'}_{a.R}x{a.C}.v"
    out.write_text(text)
    n_in = sum(w for d, w, _ in ports if d == "input")
    n_out = sum(w for d, w, _ in ports if d == "output")
    print(f"{out.relative_to(ROOT)}: {a.R * a.C} tiles, {n_in} input bits, {n_out} output bits")


if __name__ == "__main__":
    main()
