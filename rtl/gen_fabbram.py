#!/usr/bin/env python3
"""Full demo fabric with its BlockRAMs (Phase 14): rtl/bram/fab_bram.v.

FABulous's eFPGA.v with the 7 BlockRAM_1KB instances of eFPGA_top.v wired as there
(rd_addr / wr_addr / wr_data / C from FAB2RAM_*, rd_data to RAM2FAB_D, clk = UserCLK,
which eFPGA_top also drives from CLK). The eFPGA ports facing the BRAMs become internal
wires; every other port keeps its name. BlockRAM_1KB is FABulous's wrapper, unchanged;
its SRAM macro (sram_1rw1r_32_256_8_sky130, a blackbox in FABulous) is replaced by
rtl/bram/sram_model.v: write port 0 on the clock edge (chip select, write enable and
byte mask active low / high as OpenRAM), read port 1 with the address registered on the
edge; a read of the address written in the same cycle gives X (undefined for the
dual-port macro). The SRAM model carries no faults (a hard macro: memory BIST).

  python3 rtl/gen_fabbram.py   -> rtl/bram/fab_bram.v
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOP = Path("/home/user/ext/demo/Fabric/eFPGA_top.v")
EFPGA = ROOT / "rtl" / "fabric" / "eFPGA.v"
OUT = ROOT / "rtl" / "bram"

SRAM = """// SRAM macro model for simulation (no faults): OpenRAM 1rw1r 32 x 256, byte mask.
(* blackbox *)
module xgen (output wire y);
endmodule

module sram_1rw1r_32_256_8_sky130 #(
    parameter integer NUM_WMASKS = 4,
    parameter integer DATA_WIDTH = 32,
    parameter integer ADDR_WIDTH = 8,
    parameter integer RAM_DEPTH  = 1 << ADDR_WIDTH,
    parameter integer DELAY      = 3
) (
    input  wire                  clk0,
    input  wire                  csb0,
    input  wire                  web0,
    input  wire [NUM_WMASKS-1:0] wmask0,
    input  wire [ADDR_WIDTH-1:0] addr0,
    input  wire [DATA_WIDTH-1:0] din0,
    output wire [DATA_WIDTH-1:0] dout0,
    input  wire                  clk1,
    input  wire                  csb1,
    input  wire [ADDR_WIDTH-1:0] addr1,
    output wire [DATA_WIDTH-1:0] dout1
);
    reg [DATA_WIDTH-1:0] mem [0:RAM_DEPTH-1];
    reg [ADDR_WIDTH-1:0] a1;
    reg collide;
    wire we = !csb0 && !web0;
    wire x;
    xgen Inst_xgen (.y(x));
    always @(posedge clk0) begin
        if (we && wmask0[0]) mem[addr0][7:0]   <= din0[7:0];
        if (we && wmask0[1]) mem[addr0][15:8]  <= din0[15:8];
        if (we && wmask0[2]) mem[addr0][23:16] <= din0[23:16];
        if (we && wmask0[3]) mem[addr0][31:24] <= din0[31:24];
    end
    always @(posedge clk1) begin
        a1 <= addr1;
        collide <= we && (addr0 == addr1);
    end
    assign dout1 = collide ? {DATA_WIDTH{x}} : mem[a1];
    assign dout0 = {DATA_WIDTH{x}};
endmodule
"""


def main() -> None:
    OUT.mkdir(exist_ok=True)
    top = TOP.read_text()
    inst = re.search(r"\neFPGA eFPGA_inst \((.*?)\n\);", top, re.S).group(1)
    conns = re.findall(r"\.(\w+)\(([^)]*)\)", inst)
    brams = re.findall(r"\n(BlockRAM_1KB Inst_BlockRAM_\d+ \(.*?\n\);)", top, re.S)
    # eFPGA ports: direction and width from eFPGA.v
    hdr = EFPGA.read_text().split(");", 1)[0]
    ports = {n: (d, w) for d, w, n in re.findall(r"(input|output)\s*(\[[^\]]+\])?\s*(\w+)", hdr)}
    internal = {p for p, e in conns if re.match(r"(RAM2FAB_D_I|FAB2RAM_\w+)\[", e)}
    keep = [p for p in ports if p not in internal]
    lines = ["// generated by rtl/gen_fabbram.py: eFPGA + the 7 BlockRAM_1KB of eFPGA_top",
             "module fab_bram #(parameter MaxFramesPerCol = 20, parameter FrameBitsPerRow = 32) ("]
    lines.append(",\n".join(f"    {ports[p][0]} {ports[p][1] or ''} {p}".replace("  ", " ") for p in keep))
    lines.append(");")
    lines += ["wire [223:0] RAM2FAB_D_I;", "wire [223:0] FAB2RAM_D_O;", "wire [111:0] FAB2RAM_A_O;",
              "wire [55:0] FAB2RAM_C_O;", "wire CLK = UserCLK;"]
    lines.append("eFPGA eFPGA_inst (")
    lines.append(",\n".join(f"    .{p}({e if p in internal else p})" for p, e in conns if p in ports))
    lines.append(");")
    lines += brams
    lines.append("endmodule")
    (OUT / "fab_bram.v").write_text("\n".join(lines) + "\n")
    (OUT / "sram_model.v").write_text(SRAM)
    print(f"rtl/bram/fab_bram.v: {len(keep)} ports, {len(internal)} BRAM-facing ports internal, {len(brams)} BRAMs")


if __name__ == "__main__":
    main()
